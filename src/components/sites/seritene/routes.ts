const normalize = (path: string) => {
  const [pathname] = path.split(/[?#]/);
  return pathname.endsWith("/") ? pathname : pathname + "/";
};

export const isLocalRoute = (path: string) => path.startsWith("/") && LOCAL_ROUTES.has(normalize(path));
